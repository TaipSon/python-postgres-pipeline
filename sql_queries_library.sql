-- =============================================================================
-- СЛОЙ 5: ПРОДВИНУТЫЙ ETL И ОЧИСТКА ДАННЫХ (VIEWS, ПРЕОБРАЗОВАНИЕ ТИПОВ)
-- =============================================================================

-- 5.1. Создание расчетной витрины данных с трансформацией типов «на лету»
-- Вырезает текстовый маркер кубических метров, меняет разделитель и переводит строку в число.
CREATE OR REPLACE VIEW public.v_clean_walls AS
SELECT
    wall_id,
    wall_typename,
    REPLACE(REPLACE(wall_volume, 'м³', ''), ',', '.')::NUMERIC AS clean_volume
FROM public.revit_walls;


-- 5.2. Финальный расчет суммарного и среднего объема бетона на основе созданной витрины
SELECT
    SUM(clean_volume) AS total_concrete,
    AVG(clean_volume) AS avg_wall_volume
FROM public.v_clean_walls;


