-- =============================================================================
-- СЛОЙ 1: БАЗОВЫЕ ВЫБОРКИ И ЧТЕНИЕ ДАННЫХ (DQL)
-- =============================================================================

-- 1.1. Просмотр сырых данных, импортированных из CSV-файла выгрузки Revit
SELECT * 
FROM public.revit_walls;


-- 1.2. Выборка конкретных столбцов с переименованием (Алиасы для бизнес-отчетов)
SELECT 
    element_id AS паспорт_стены,
    element_vol AS сырой_объем_бетона
FROM public.staging_walls;


-- =============================================================================
-- СЛОЙ 2: ФИЛЬТРАЦИЯ, ПОИСК И СОРТИРОВКА (WHERE, LIKE, ORDER BY)
-- =============================================================================

-- 2.1. Фильтрация по точному совпадению марки с сортировкой по убыванию объема
SELECT *
FROM public.staging_walls
WHERE element_name = 'В30 200мм'
ORDER BY element_vol DESC;


-- 2.2. Поиск по части слова (Мягкая фильтрация элементов, содержащих определенную марку бетона)
SELECT *
FROM public.staging_walls
WHERE element_name LIKE '%В30%';


-- =============================================================================
-- СЛОЙ 3: АГРЕГАЦИЯ И ГРУППИРОВКА (COUNT, GROUP BY)
-- =============================================================================

-- 3.1. Подсчет количества конструкций, сгруппированных по их типам
SELECT 
    element_name, 
    COUNT(*) AS количество_штук
FROM public.staging_walls
GROUP BY element_name;


-- =============================================================================
-- СЛОЙ 4: УПРАВЛЕНИЕ СТРУКТУРОЙ И ЦЕЛОСТНОСТЬ ДАННЫХ (DDL & DML)
-- =============================================================================

-- 4.1. Пересоздание таблицы с определением типов данных и автоинкрементным первичным ключом
DROP TABLE IF EXISTS public.staging_walls;

CREATE TABLE public.staging_walls (
    id SERIAL PRIMARY KEY,              -- Уникальный порядковый номер записи
    element_id INT NOT NULL,            -- Идентификатор элемента из BIM-модели
    element_name VARCHAR(255),          -- Наименование/марка элемента
    element_vol VARCHAR(50)             -- Текстовое поле для сырого объема
);


-- 4.2. Ручное заполнение таблицы тестовыми данными для проверки структуры пайплайна
