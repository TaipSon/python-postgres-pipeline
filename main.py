import sys
from io import StringIO
import json
import pandas as pd
import ollama  # Локальный интерфейс для запуска и взаимодействия с LLM (Qwen)

# ==============================================================================
# 1. НАСТРОЙКА ОТОБРАЖЕНИЯ ТАБЛИЦ В КОНСОЛИ
# ==============================================================================
pd.set_option('display.max_columns', None)
pd.set_option('display.width', 1000)

# ==============================================================================
# 2. ЗАГРУЗКА И СЧИТЫВАНИЕ CSV-ФАЙЛА (ЭТАП TRANSFORMATION)
# ==============================================================================
csv_path = r"E:\BIM_Data_Project1\walls_data.csv"
df = pd.read_csv(csv_path, sep=';')

# ==============================================================================
# 3. ОЧИСТКА ДАННЫХ И ПРИВЕДЕНИЕ ТИПОВ (ДАТА-КЛИНИНГ)
# ==============================================================================
df['clean_vol'] = df['element_vol'].str.replace('м³', '').str.replace(',', '.').astype(float)

# ==============================================================================
# 4. РАСЧЕТ СМЕТНОЙ СТОИМОСТИ МАТЕРИАЛОВ (БИЗНЕС-ЛОГИКА)
# ==============================================================================
def get_price_per_m3(name):
    if 'В30' in str(name):    
        return 6500.0  # Цена за кубический метр бетона марки В30
    if 'В25' in str(name):    
        return 5800.0  # Цена за кубический метр бетона марки В25
    return 5000.0      # Дефолтная стоимость для прочих марок

df['price_per_m3'] = df['element_name'].apply(get_price_per_m3)
df['total_wall_cost'] = df['clean_vol'] * df['price_per_m3'].round(2)

# Переименуем колонки в исходном df на понятный русский язык для ИИ-агента
df.columns = ['ID элемента', 'Марка бетона', 'Сырой объем', 'Объем стены м³', 'Цена за м³ руб', 'Итоговая стоимость стены руб']

# ==============================================================================
# 5. ENGINE ДЛЯ АГЕНТСКОГО ИИ (ДИНАМИЧЕСКОЕ ВЫПОЛНЕНИЕ PYTHON-КОДА)
# ==============================================================================
def execute_python_code(code_string):
    old_stdout = sys.stdout
    redirected_output = sys.stdout = StringIO()
    
    # ИИ-агент имеет доступ к единому датафрейму df, где хранятся все данные
    local_vars = {
        'df': df
    }
    
    try:
        exec(code_string, {}, local_vars)
        sys.stdout = old_stdout
        return redirected_output.getvalue().strip()
    except Exception as e:
        sys.stdout = old_stdout
        return f"Ошибка при расчете: {e}"

# ==============================================================================
# 6. НАСТРОЙКА ИНСТРУКЦИЙ ДЛЯ ИИ-АГЕНТА (РАЗДЕЛЕНИЕ ДИАЛОГА И АНАЛИТИКИ)
# ==============================================================================
system_prompt = """
Ты — ИИ-Агент, продвинутый аналитик BIM-данных и сметной стоимости.
У тебя есть доступ ровно к ОДНОМУ датафрейму Pandas под названием `df`.

Колонки в таблице `df`:
- 'ID элемента' — уникальный номер стены
- 'Марка бетона' — название и марка конструкции (например, B25, B30)
- 'Объем стены м³' — чистый объем бетона для ОДНОЙ конкретной стены
- 'Цена за м³ руб' — стоимость одного кубического метра бетона
- 'Итоговая стоимость стены руб' — рассчитанная полная стоимость ОДНОЙ конкретной стены

ПРАВИЛО СВЕТСКОЙ БЕСЕДЫ (ПРИВЕТСТВИЯ И ПРОСТЫЕ РЕПЛИКИ):
Если пользователь просто здоровается («Привет», «Здравствуйте»), прощается («Пока»), благодарит («Спасибо») или пишет простые бытовые реплики, которые НЕ содержат вопросов про данные, объемы, количество или стоимость — ты НЕ должен писать никакой Python-код. Ответь как обычный вежливый человек коротким текстом на русском языке, без использования тегов ```python.

ПРАВИЛО АНАЛИТИКИ (КОГДА ЕСТЬ ВОПРОС ПО ТАБЛИЦЕ):
Если пользователь просит что-то посчитать, узнать сумму, объемы, цены или количество — ты физически НЕ умеешь считать сам. Ты ОБЯЗАН написать Python-код, который выведет ПОЛНЫЙ ответ через функцию print() с использованием f-строк.
Твой ответ в этом случае должен состоять СТРОГО из блока кода в тегах ```python ... ```. Никакого текста вне тегов писать не нужно.

Примеры аналитических ответов:

Вопрос: какой общий объем бетона?
Ответ:
```python
print(f"Общий объем бетона во всем проекте составляет {df['Объем стены м³'].sum():.2f} м³.")
```

Вопрос: какая максимальная стоимость стены?
Ответ:
```python
print(f"Максимальная стоимость одной конструкции в проекте — {df['Итоговая стоимость стены руб'].max():,.2f} руб.")
```

Вопрос: минимальный объем стены бетона
Ответ:
```python
print(f"Минимальный объем отдельной стены составляет {df['Объем стены м³'].min():.2f} м³.")
```

ЯЗЫКОВОЕ ПРАВИЛО:
Ты обязан общаться СТРОГО на русском языке. Использование китайских иероглифов категорически ЗАПРЕЩЕНО.
"""

# Стартовое информационное сообщение в консоли при запуске утилиты
print("\n" + "="*60)
print(" 🚀 AGENTIC AI ЗАПУЩЕН НА RTX 3070!")
print(" Теперь модель генерирует точные ответы на базе динамического кода.")
print(" Чтобы завершить общение, напишите: выход")
print("="*60 + "\n")

# Инициализируем историю диалога с контекстом системных инструкций
chat_history = [{'role': 'system', 'content': system_prompt}]

# ==============================================================================
# 7. РАБОЧИЙ ЦИКЛ С ИСПРАВЛЕННЫМ ПАРСИНГОМ И ПОДДЕРЖКОЙ ОБЫЧНОГО ДИАЛОГА
# ==============================================================================
while True:
    user_input = input("Вы: ")
    if user_input.lower().strip() in ['выход', 'exit', 'quit', 'стоп']:
        print("\nДиалог завершен. До связи!")
        break
    if not user_input.strip():
        continue
        
    chat_history.append({'role': 'user', 'content': user_input})
    print("Робот думает...", end="\(\r\)")  # Эффект загрузки в текущей строке консоли
    
    try:
        # Запрашиваем ответ у ИИ
        response = ollama.chat(
            model='qwen2.5:3b',
            messages=chat_history,
            options={'temperature': 0.1}  # Низкая температура для максимальной точности кода
        )
        ai_raw_response = response['message']['content']
        
        if "```python" in ai_raw_response:
            # Если модель сгенерировала код, извлекаем его по индексам строк
            parts = ai_raw_response.split("```python")
            code_block = parts[1].split("```")[0].strip()
            
            # Выполняем сгенерированный код на реальной таблице df
            execution_result = execute_python_code(code_block)
            
            # Очищаем строку "Робот думает..." и выводим чистый результат работы print()
            print(" " * 20, end="\r")
            print(f"Ответ ИИ: {execution_result}")
            print("-" * 50)
            
            # Сохраняем сгенерированный код в историю, чтобы модель помнила контекст расчетов
            chat_history.append({'role': 'assistant', 'content': ai_raw_response})
        else:
            # Если это обычная беседа (приветствие) без кода, просто выводим текст
            clean_text = ai_raw_response.replace("**", "").replace("#", "")
            print(" " * 20, end="\r")
            print(f"Ответ ИИ: {clean_text}")
            print("-" * 50)
            chat_history.append({'role': 'assistant', 'content': ai_raw_response})
            
    except Exception as e:
        print(f"\n[ОШИБКА ИСПОЛНЕНИЯ]: {e}\n")

